#!/usr/bin/env node
/**
 * Compile the simulators' Tailwind utilities into a static stylesheet.
 *
 * Until now all nine simulator pages loaded the Tailwind Play CDN:
 *
 *   <script src="https://cdn.tailwindcss.com/3.4.17"></script>
 *   <script src="/assets/js/simulator-tailwind-config.js"></script>
 *
 * That is the whole Tailwind compiler -- around 400 KB of JavaScript, parsed
 * and executed on the visitor's device, which then scans the document, builds
 * the utility CSS the page needs and injects it into a <style> element. It is
 * a development convenience that Tailwind's own documentation says not to ship,
 * and on this site it sat in front of the largest contentful paint of every
 * simulator page: nothing on the console can be laid out until the compiler has
 * downloaded, run and produced the styles, and the field data for these pages
 * was a p75 LCP of 3062 ms against a 2500 ms budget.
 *
 * This script does the same work once, here, and commits the answer. The pages
 * link the result as ordinary CSS.
 *
 * WHY IT IS NOT PART OF `npm run build`
 *
 * Tailwind is not a dependency of this repository and is deliberately not being
 * made one -- it is needed to regenerate one committed file, not to deploy the
 * site, and a devDependency that only one maintenance script imports is a
 * dependency the deploy has to install on every build for no reason. Same
 * arrangement as scripts/build-font-awesome-subset.py.
 *
 * Install it when you need it:
 *
 *   npm install --no-save tailwindcss@3.4.17 postcss
 *   node scripts/build-simulator-css.mjs
 *
 * WHAT KEEPS THE OUTPUT HONEST IF NOBODY REMEMBERS TO RUN IT
 *
 * scripts/check-class-coverage.mjs. The nine simulator pages used to be on its
 * advisory list, skipped outright because a class compiled in the browser from
 * a config the checker cannot evaluate is not a class it can verify. Now that
 * the utilities are in a stylesheet it can read, they are checked strictly like
 * every other hand-maintained page: add `md:gap-7` to a simulator without
 * regenerating this file and `npm run check` says so by name and line.
 *
 * WHY 3.4.17
 *
 * The version the pages pinned on the CDN, so the compiled output is the CSS
 * those pages were authored against. Tailwind 4 changes the config format
 * (CSS-first `@theme` rather than a JavaScript object) and re-points several
 * default scales; moving to it is a migration, not a version bump, and it is
 * not one worth bundling into a performance fix.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { SIMULATOR_THEME_EXTEND } from './lib/simulator-theme.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'assets/css/simulator-tailwind.css';

/** The nine pages, in the order the site lists them. */
const PAGES = ['data-governance-day-to-day', 'data-literacy', 'data-ownership-conflict']
  .flatMap((slug) => ['en', 'es', 'pt'].map((lang) => `simulators/${lang}/${slug}/index.html`));

/**
 * Everything Tailwind has to read to know which utilities the pages use.
 *
 * The pages themselves are most of it -- each one carries its whole simulator
 * inline, markup and logic together, so a class only ever mentioned in a
 * template literal (`class="px-2.5 py-1 rounded-md border ${colorClass}"`, with
 * `colorClass` assigned `'text-emerald-400 border-emerald-500/30'` fifty lines
 * up) is still in the same file and still found.
 *
 * The rest is the shared scripts those pages load, which build the leaderboard
 * rows, the welcome dialog and the private-space chrome from class names that
 * appear nowhere in the HTML. Rather than list them and let the list rot, they
 * are read out of the pages' own <script src> attributes.
 */
const contentFiles = async () => {
  const files = new Set(PAGES.map((page) => path.join(ROOT, page)));
  for (const page of PAGES) {
    const html = await readFile(path.join(ROOT, page), 'utf8');
    for (const match of html.matchAll(/<script\b[^>]*\bsrc="(\/assets\/js\/[^"]+)"/g)) {
      files.add(path.join(ROOT, match[1].slice(1)));
    }
  }
  return [...files].sort();
};

const HEADER = `/*
 * Generated by scripts/build-simulator-css.mjs -- do not edit by hand.
 *
 * Tailwind CSS __VERSION__, compiled against scripts/lib/simulator-theme.mjs and
 * the nine simulator pages. Regenerate after changing either:
 *
 *   npm install --no-save tailwindcss@3.4.17 postcss
 *   node scripts/build-simulator-css.mjs
 *
 * Loaded where the Play CDN script used to sit -- before simulator-header.css,
 * simulator-theme.css and font-awesome.css, so those still win a specificity
 * tie against a utility, exactly as they did when the compiler injected its
 * <style> element at that point in the head.
 */
`;

const load = async (specifier) => {
  try {
    return await import(specifier);
  } catch {
    throw new Error(
      `${specifier} is not installed. This script is not part of the deploy build; ` +
        'install its tools first:\n\n  npm install --no-save tailwindcss@3.4.17 postcss\n',
    );
  }
};

const main = async () => {
  const postcss = (await load('postcss')).default;
  const tailwindcss = (await load('tailwindcss')).default;
  const { version } = JSON.parse(
    await readFile(path.join(await resolveTailwindDir(), 'package.json'), 'utf8'),
  );

  const content = await contentFiles();
  const result = await postcss([
    tailwindcss({
      content,
      // Utilities only ever appear in a class attribute or a string literal in
      // these files; nothing here relies on Tailwind reading a `.jsx`-style
      // expression, so the stock extractor is enough.
      theme: { extend: SIMULATOR_THEME_EXTEND },
      corePlugins: { preflight: true },
    }),
  ]).process('@tailwind base;\n@tailwind components;\n@tailwind utilities;\n', {
    from: undefined,
  });

  await mkdir(path.join(ROOT, path.dirname(OUTPUT)), { recursive: true });
  await writeFile(
    path.join(ROOT, OUTPUT),
    `${HEADER.replace('__VERSION__', version)}\n${result.css.trim()}\n`,
    'utf8',
  );

  const bytes = Buffer.byteLength(result.css, 'utf8');
  console.log(`${OUTPUT}: ${(bytes / 1024).toFixed(1)} KB from ${content.length} source files`);
};

/** Where the ad-hoc install put Tailwind, so its version can be recorded. */
const resolveTailwindDir = async () => {
  const entry = fileURLToPath(import.meta.resolve('tailwindcss'));
  let dir = path.dirname(entry);
  while (path.basename(dir) !== 'tailwindcss' && dir !== path.dirname(dir)) dir = path.dirname(dir);
  return dir;
};

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
