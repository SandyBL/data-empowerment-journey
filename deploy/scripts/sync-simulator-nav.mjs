#!/usr/bin/env node
/**
 * Writes the site navigation into the nine simulator pages.
 *
 * Every other page family on this site renders its header from
 * scripts/lib/site-nav.mjs at build time. The simulators cannot: each one is a
 * standalone HTML file that carries its whole app inline and is served straight
 * off the filesystem, which is deliberate -- a simulator loads and plays with no
 * database, no API and no build step. The cost of that was navigational. Their
 * header ended in a single home icon, so a page opened from a search result
 * offered exactly one way onward: the homepage, and nothing else on the site was
 * reachable without going through it.
 *
 * So the markup is generated here instead, from the same NAV_GROUPS the header,
 * the drawer, the footer directory and the sitemap are generated from, and
 * written into the nine files between markers. The pages carry a copy of the
 * links; they do not carry a second list of them. When the navigation changes,
 * `npm run sync:simulator-nav` puts the change in all nine, and the diff shows
 * exactly which pages moved.
 *
 * It is not part of `npm run build`. The build writes into ignored output
 * directories and leaves the tree clean; this rewrites tracked source, which is
 * a thing a person does on purpose and reviews, not something that happens
 * during a deploy.
 *
 * Safe to run twice: the markers are replaced in place, and the stylesheet and
 * script tags are added only when they are absent. `--check` reports what would
 * change and writes nothing.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { renderNavDrawer, renderNavToggle } from './lib/site-nav.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The nine pages, and which navigation item each of them *is*.
 *
 * The key is a NAV key, which is what the drawer marks with
 * `aria-current="page"`: a visitor inside the literacy simulator opens the menu
 * and can see that "Data literacy" under Practice is where they already are.
 */
const SIMULATORS = [
  { slug: 'data-governance-day-to-day', current: 'simDayToDay' },
  { slug: 'data-literacy', current: 'simLiteracy' },
  { slug: 'data-ownership-conflict', current: 'simOwnership' },
];

const LANGUAGES = ['en', 'es', 'pt'];

const STYLESHEET = '<link rel="stylesheet" href="/assets/css/site-chrome.css">';
const SCRIPT = '<script type="module" src="/assets/js/site-nav.js"></script>';

const TOGGLE_MARK = 'dgj:nav-toggle';
const DRAWER_MARK = 'dgj:nav-drawer';

const GENERATED = 'generated by scripts/sync-simulator-nav.mjs -- edit scripts/lib/site-nav.mjs';

/** `<!-- dgj:x -->…<!-- /dgj:x -->`, replaced whole when it is already there. */
const writeBlock = (html, mark, body, indent) => {
  const open = `<!-- ${mark}: ${GENERATED} -->`;
  const close = `<!-- /${mark} -->`;
  const block = `${indent}${open}\n${indent}${body}\n${indent}${close}`;
  const existing = new RegExp(`[ \\t]*<!-- ${mark}:[\\s\\S]*?<!-- /${mark} -->`);
  return existing.test(html) ? { html: html.replace(existing, block), block } : { html: null, block };
};

/** The indentation of the first line matching `pattern`, so the block lines up. */
const indentOf = (html, pattern) => {
  const match = html.match(pattern);
  if (!match) throw new Error(`cannot find ${pattern} to indent against`);
  return match[1];
};

const patch = (html, lang, current) => {
  const notes = [];

  /* --------------------------------------------------------- the toggle -- */

  const actionIndent = indentOf(html, /^([ \t]*)<a href="[^"]*" class="simulator-home-link"/m);
  const toggle = writeBlock(html, TOGGLE_MARK, renderNavToggle(lang), actionIndent);
  if (toggle.html) {
    html = toggle.html;
    notes.push('toggle updated');
  } else {
    // After the home link, so the menu is the last control in the row -- the
    // same place it sits in the site header.
    const homeLink = /^[ \t]*<a href="[^"]*" class="simulator-home-link"[\s\S]*?<\/a>\n/m;
    if (!homeLink.test(html)) throw new Error('no .simulator-home-link to insert the toggle after');
    html = html.replace(homeLink, (found) => `${found}${toggle.block}\n`);
    notes.push('toggle added');
  }

  /* --------------------------------------------------------- the drawer -- */

  const innerIndent = indentOf(html, /^([ \t]*)<div class="simulator-site-header-inner">/m);
  const drawer = writeBlock(html, DRAWER_MARK, renderNavDrawer(lang, { current }), innerIndent);
  if (drawer.html) {
    html = drawer.html;
    notes.push('drawer updated');
  } else {
    // Inside the header, which is sticky and therefore the containing block the
    // drawer's `top: 100%` resolves against, and whose stacking context puts it
    // over the app shell it covers.
    const headerClose = /^([ \t]*)<\/header>/m;
    if (!headerClose.test(html)) throw new Error('no </header> to insert the drawer before');
    html = html.replace(headerClose, (found) => `${drawer.block}\n${found}`);
    notes.push('drawer added');
  }

  /* ------------------------------------------------- stylesheet, script -- */

  if (!html.includes(STYLESHEET)) {
    const sheet = /^([ \t]*)<link rel="stylesheet" href="\/assets\/css\/simulator-header\.css">\n/m;
    if (!sheet.test(html)) throw new Error('no simulator-header.css link to add site-chrome.css after');
    html = html.replace(sheet, (found, indent) => `${found}${indent}${STYLESHEET}\n`);
    notes.push('stylesheet added');
  }

  if (!html.includes(SCRIPT)) {
    if (!html.includes('</body>')) throw new Error('no </body> to add the navigation script before');
    html = html.replace('</body>', `${SCRIPT}\n</body>`);
    notes.push('script added');
  }

  return { html, notes };
};

const main = async () => {
  const checkOnly = process.argv.includes('--check');
  let changed = 0;

  for (const lang of LANGUAGES) {
    for (const simulator of SIMULATORS) {
      const relative = path.join('simulators', lang, simulator.slug, 'index.html');
      const file = path.join(ROOT, relative);
      const before = await readFile(file, 'utf8');
      const { html, notes } = patch(before, lang, simulator.current);

      if (html === before) {
        console.log(`  unchanged  ${relative}`);
        continue;
      }
      changed += 1;
      console.log(`  ${checkOnly ? 'would write' : 'wrote'}      ${relative}  (${notes.join(', ')})`);
      if (!checkOnly) await writeFile(file, html);
    }
  }

  console.log(`\nsimulator navigation: ${changed} of 9 pages ${checkOnly ? 'would change' : 'changed'}`);
  if (checkOnly && changed) process.exitCode = 1;
};

main().catch((error) => {
  console.error(`sync-simulator-nav: ${error.message}`);
  process.exitCode = 1;
});
